import { useState, type CSSProperties } from 'react'
import { media, type MediaKey } from '../../data/media.generated'
import { cn } from '../../lib/hooks'

interface ImgProps {
  k: MediaKey
  alt: string
  /** Responsive sizes attribute. Defaults to full viewport width. */
  sizes?: string
  className?: string
  imgClassName?: string
  /** Above-the-fold: eager + high fetch priority (use for LCP images only). */
  priority?: boolean
  fit?: 'cover' | 'contain'
  position?: string
  style?: CSSProperties
  /** Render as a fill layer (absolute inset-0) instead of intrinsic ratio. */
  fill?: boolean
}

/**
 * Responsive WebP image with intrinsic dimensions (no CLS), blur-up placeholder,
 * and lazy loading by default. All sources are generated by `npm run images`.
 */
export function Img({ k, alt, sizes = '100vw', className, imgClassName, priority, fit = 'cover', position = '50% 50%', style, fill }: ImgProps) {
  const asset = media[k]
  const [loaded, setLoaded] = useState(false)
  if (!asset) return null
  const srcSet = asset.srcs.map((s) => `${s.src} ${s.w}w`).join(', ')
  const fallback = asset.srcs[Math.min(1, asset.srcs.length - 1)].src

  return (
    <div
      className={cn('relative overflow-hidden', fill && 'absolute inset-0', className)}
      style={{
        ...(fill ? {} : { aspectRatio: `${asset.width} / ${asset.height}` }),
        backgroundImage: loaded ? undefined : `url("${asset.lqip}")`,
        backgroundSize: 'cover',
        backgroundPosition: position,
        ...style,
      }}
    >
      <img
        src={fallback}
        srcSet={srcSet}
        sizes={sizes}
        width={asset.width}
        height={asset.height}
        alt={alt}
        loading={priority ? 'eager' : 'lazy'}
        decoding={priority ? 'sync' : 'async'}
        fetchPriority={priority ? 'high' : 'auto'}
        onLoad={() => setLoaded(true)}
        ref={(el) => {
          if (el?.complete && el.naturalWidth) setLoaded(true)
        }}
        className={cn(
          'h-full w-full transition-opacity duration-700',
          loaded || priority ? 'opacity-100' : 'opacity-0',
          imgClassName,
        )}
        style={{ objectFit: fit, objectPosition: position }}
      />
    </div>
  )
}

export const mediaSrc = (k: MediaKey, w = 1600) => {
  const a = media[k]
  return (a.srcs.find((s) => s.w >= w) ?? a.srcs[a.srcs.length - 1]).src
}
